test('finish verifies real saved sources and distinguishes partial generation or Agent failure', t => {
  const f = fixture(t)
  f.begin({ targetSources: 1 })
  f.search(['https://example.com/a'])
  f.fetch('https://example.com/a')
  f.research.update(f.workspace.id, { artifactStatus: 'failed', artifactError: 'Generation failed' })
  const artifactFailure = f.research.finish(f.workspace.id, { status: 'done' })
  assert.equal(artifactFailure.status, 'partial')
  assert.equal(artifactFailure.error, 'Generation failed')
  f.begin({ targetSources: 1 })
  f.search(['https://example.com/a'])
  f.fetch('https://example.com/a')
  assert.equal(f.research.finish(f.workspace.id, { status: 'failed', error: 'Model failed' }).status, 'partial')
  f.begin({ targetSources: 1 })
  f.search(['https://example.com/a'])
  f.fetch('https://example.com/a')
  const sourceId = f.status().reused[0].sourceId
  f.library.deleteSource(f.notebook.id, sourceId)
  assert.equal(f.research.finish(f.workspace.id, { status: 'done' }).status, 'failed')
})

