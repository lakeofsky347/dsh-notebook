import { openLibrary } from '../src/library.js'
import { createResearch } from '../src/research.js'

const limits = {
  maxNotebooks: 20, maxSourcesPerNotebook: 20, maxWordsPerSource: 10000,
  maxUploadBytes: 100000, maxUrlBytes: 100000, chunkChars: 100, chunkOverlap: 10, topK: 3,
}

function fixture(t, { file = ':memory:', maxSources = 12 } = {}) {
  const library = openLibrary(file, limits)
  t.after(() => library.close())
  const notebook = library.createNotebook({ title: 'Research' })
  const workspace = library.createWorkspace({ title: 'Research' })
  library.bind('workbench:' + workspace.id, notebook.id)
  const changes = []
  const research = createResearch(library, { maxSources, onNotebookChange: id => changes.push(id) })
  const begin = (extra = {}) => research.begin(workspace.id, { notebookId: notebook.id, prompt: '研究海洋碳汇的方法与争议', targetSources: 2, ...extra })
  const execution = (name, args = {}, extra = {}) => ({ name, arguments: args, agent: { id: workspace.id }, callId: randomUUID(), token: Symbol(name), signal: new AbortController().signal, ...extra })
  const search = (urls, extra = {}) => research.observe(execution('web_search', { queries: ['海洋碳汇 一手资料'] }, extra), {
    isError: false, value: { sources: urls.map((url, index) => ({ url, title: 'Source ' + index, snippet: 'Search snippet only' })), truncated: false },
  })
  const fetch = (url, extra = {}, value = {}) => research.observe(execution('web_fetch', { url }, extra), {
    isError: false, value: { url, statusCode: 200, body: { kind: 'text', content: 'Verified page body for ' + url }, truncated: false, ...value },
  })
  return { library, research, notebook, workspace, changes, begin, execution, search, fetch, status: () => research.status(workspace.id) }
}

test('research saves only fetched search candidates and completes from persisted sources', t => {
  const f = fixture(t)
  const run = f.begin()
  assert.equal(run.phase, 'planning')
  assert.equal(run.id, run.runId)
  f.search(['https://example.com/a', 'https://example.com/b'])
  assert.equal(f.library.listSources(f.notebook.id).length, 0)
  assert.equal(f.status().phase, 'searching')
  assert.deepEqual(f.status().queries, ['海洋碳汇 一手资料'])
  f.fetch('https://example.com/unsolicited')
  assert.equal(f.library.listSources(f.notebook.id).length, 0)
  f.fetch('https://example.com/a')
  f.fetch('https://example.com/b', {}, { truncated: true })
  const saved = f.library.listSources(f.notebook.id)
  assert.equal(saved.length, 2)
  assert.equal(f.library.getSource(f.notebook.id, saved[0].id).body.includes('Search snippet only'), false)
  assert.equal(f.status().candidates[1].truncated, true)
  assert.equal(f.status().phase, 'importing')
  assert.deepEqual(f.changes, [f.notebook.id, f.notebook.id])
  assert.match(f.research.instructions(f.workspace.id), /已收录 2 个/)
  f.research.update(f.workspace.id, { phase: 'synthesizing', artifactId: 'guide', artifactStatus: 'done' })
  const final = f.research.finish(f.workspace.id, { status: 'done' })
  assert.equal(final.status, 'done')
  assert.equal(final.completedSources, 2)
  assert.equal(final.artifactId, 'guide')
  assert.equal(f.research.instructions(f.workspace.id), '')
  assert.equal(f.library.listMessages(f.workspace.id).length, 1)
})

test('URL normalization deduplicates fragments, preserves query identity and rejects non-web credentials', t => {
  const f = fixture(t)
  f.begin({ targetSources: 1 })
  f.search(['https://EXAMPLE.com:443/a#one', 'https://example.com/a#two', 'https://example.com/a?edition=2', 'file:///tmp/source', 'https://user:password@example.com/a'])
  assert.deepEqual(f.status().candidates.map(candidate => candidate.url), ['https://example.com/a', 'https://example.com/a?edition=2'])
  f.fetch('https://example.com/a#one')
  f.fetch('https://example.com/a#two')
  f.fetch('https://example.com/a?edition=2')
  assert.equal(f.library.listSources(f.notebook.id).length, 1)
  assert.equal(f.status().completedSources, 1)
})

