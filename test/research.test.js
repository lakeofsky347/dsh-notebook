test('research snapshots survive database reopen and running tasks recover as interrupted', t => {
  const dir = mkdtempSync(join(tmpdir(), 'dsh-research-'))
  t.after(() => rmSync(dir, { recursive: true, force: true }))
  const file = join(dir, 'library.sqlite')
  const first = openLibrary(file, limits)
  const notebook = first.createNotebook({ title: 'Persistent research' })
  const workspace = first.createWorkspace()
  first.bind('workbench:' + workspace.id, notebook.id)
  const initial = createResearch(first)
  const original = initial.begin(workspace.id, { notebookId: notebook.id, prompt: 'A topic', targetSources: 1 })
  const artifact = first.createArtifact(notebook.id, { kind: 'study-guide', title: 'Pending guide' })
  initial.update(workspace.id, { phase: 'synthesizing', artifactId: artifact.id, artifactStatus: 'running' })
  first.close()
  const second = openLibrary(file, limits)
  t.after(() => second.close())
  const resumed = createResearch(second)
  assert.equal(resumed.status(workspace.id).id, original.id)
  assert.equal(resumed.status(workspace.id).artifactId, artifact.id)
  const recovered = resumed.recover()
  assert.equal(recovered.length, 1)
  assert.equal(recovered[0].status, 'interrupted')
  assert.equal(recovered[0].artifactStatus, 'failed')
  assert.match(recovered[0].artifactError, /未生成完成/)
  assert.equal(second.getArtifact(artifact.id).status, 'failed')
  assert.equal(second.getArtifact(artifact.id).error, recovered[0].artifactError)
  assert.equal(resumed.recover().length, 0)
  assert.equal(second.listMessages(workspace.id)[0].metadata.research.status, 'interrupted')
  resumed.begin(workspace.id, { notebookId: notebook.id, prompt: 'Try again', targetSources: 1 })
  assert.equal(second.listMessages(workspace.id).length, 2)
  assert.equal(resumed.status(workspace.id).prompt, 'Try again')
})

test('recovery leaves completed artifacts and artifacts belonging to another notebook intact', t => {
  const f = fixture(t)
  f.begin({ targetSources: 1 })
  const completed = f.library.createArtifact(f.notebook.id, { kind: 'study-guide', title: 'Done' })
  f.library.finishArtifact(completed.id, 'done', 'Completed body')
  f.research.update(f.workspace.id, { artifactId: completed.id, artifactStatus: 'done' })
  f.research.recover()
  assert.equal(f.library.getArtifact(completed.id).status, 'done')
  assert.equal(f.status().artifactStatus, 'done')
  const other = f.library.createNotebook({ title: 'Other' })
  const pending = f.library.createArtifact(other.id, { kind: 'study-guide', title: 'Not this run' })
  f.begin({ targetSources: 1 })
  f.research.update(f.workspace.id, { artifactId: pending.id, artifactStatus: 'running' })
  f.research.recover()
  assert.equal(f.library.getArtifact(pending.id).status, 'pending')
})

